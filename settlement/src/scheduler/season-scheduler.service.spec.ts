import { Test, TestingModule } from '@nestjs/testing';
import { getDataSourceToken, getRepositoryToken } from '@nestjs/typeorm';
import {
  LeagueEntity,
  LeagueStandingEntity,
  MatchEntity,
  MatchStatus,
  MatchType,
  GAME_SETTINGS,
  computeSeasonWeekOneMonday,
  startOfUtcDay,
} from '@goalxi/database';
import { SeasonSchedulerService } from './season-scheduler.service';
import { ScheduleGenerator } from '../bootstrap/generators/schedule.generator';
import { LOGGER_SERVICE_PROVIDER } from '../test-utils/test-logger';

/**
 * Season 2+ fixture generation.
 *
 * These are the only paths through `SeasonSchedulerService` — season 1
 * is generated by `bootstrap/generators/schedule.generator.ts`, which
 * derives kickoff times with `matchStart(round, weekOneMonday)`. That
 * divergence is why the bug this file pins was invisible in season 1
 * and produced a broken fixture list from season 2 onward.
 */
describe('SeasonSchedulerService', () => {
  let service: SeasonSchedulerService;
  let matchRepository: {
    save: jest.Mock;
    count: jest.Mock;
  };
  let leagueRepository: { find: jest.Mock };
  let standingRepository: { find: jest.Mock };
  let dataSource: { manager: { findOne: jest.Mock } };

  const TEAM_IDS = Array.from({ length: 16 }, (_, i) => `team-${i + 1}`);
  // A **Monday**, so the week-one anchor is START itself: round 0 lands on
  // `MATCH_DAY_OFFSETS[0]` (Tuesday) and the anchor walks back exactly one
  // day to START. With a non-Monday START the tests would have to
  // re-derive the anchor, which is the calculation they are trying to check.
  const START = new Date('2026-04-06T00:00:00.000Z'); // Mon
  const WEEK_ONE_MONDAY = START;
  // A Monday, matching what `resolveInitDate` returns in production.
  const INIT_DATE = new Date('2026-04-06T00:00:00.000Z'); // Mon
  const MS_WEEK = 7 * 24 * 60 * 60 * 1000;

  beforeEach(async () => {
    matchRepository = {
      save: jest.fn().mockImplementation((m) => m),
      count: jest.fn().mockResolvedValue(0),
    };
    leagueRepository = { find: jest.fn().mockResolvedValue([]) };
    standingRepository = { find: jest.fn().mockResolvedValue([]) };
    // `resolveInitDate` reads the singleton `system_config.init_date`
    // row; returning null makes it fall back to `resolveGameStart(env)`,
    // which these tests leave unset.
    dataSource = { manager: { findOne: jest.fn().mockResolvedValue(null) } };
    const module: TestingModule = await Test.createTestingModule({
      providers: [
        SeasonSchedulerService,
        LOGGER_SERVICE_PROVIDER,
        { provide: getRepositoryToken(MatchEntity), useValue: matchRepository },
        {
          provide: getRepositoryToken(LeagueEntity),
          useValue: leagueRepository,
        },
        {
          provide: getRepositoryToken(LeagueStandingEntity),
          useValue: standingRepository,
        },
        { provide: getDataSourceToken(), useValue: dataSource },
      ],
    }).compile();
    service = module.get(SeasonSchedulerService);
  });

  const gen = () =>
    (service as any).generateDoubleRoundRobin(
      TEAM_IDS,
      'league-1',
      2,
      START,
    ) as Partial<MatchEntity>[];

  it('gives every match a defined kickoff time', () => {
    // The old code fell back to `firstLegDates[round * 2]` when
    // `firstLegDates[round * 2 + i]` was undefined, which silently
    // collapsed 6 of the last round's 8 matches onto one timestamp
    // (and most of the second leg likewise).
    const matches = gen();
    expect(matches.length).toBe(16 * 15); // double round-robin
    for (const m of matches) {
      expect(m.scheduledAt).toBeInstanceOf(Date);
      expect(Number.isNaN((m.scheduledAt as Date).getTime())).toBe(false);
    }
  });

  it('REGRESSION: all matches sharing a kickoff time form one full matchday', () => {
    // `dates[round * 2 + i]` with `i` = match-within-round spread a
    // single matchday across four calendar weeks (Wed r0, Sat r0,
    // Wed r1, Sat r1, ...).
    //
    // NOTE: the `round` column is `(r % 2) + 1` — it encodes which day
    // of the match-week (1 = Wed, 2 = Sat), NOT the calendar round, so
    // it cannot be used to group. Group by timestamp instead.
    const byTimestamp = new Map<number, Partial<MatchEntity>[]>();
    for (const m of gen()) {
      const key = (m.scheduledAt as Date).getTime();
      byTimestamp.set(key, [...(byTimestamp.get(key) ?? []), m]);
    }
    // 16 teams / 2 = 8 matches per matchday; 15 rounds x 2 legs = 30 slots.
    expect(byTimestamp.size).toBe(30);
    for (const [ts, group] of byTimestamp) {
      expect({ ts, matches: group.length }).toEqual({ ts, matches: 8 });
    }
  });

  it('REGRESSION: no timestamp collision across the season', () => {
    // Before the fix, six matches in round 14 (and most of leg 2)
    // shared the single fallback timestamp — i.e. some timestamps
    // carried far more than one matchday's worth of matches.
    const matches = gen();
    const counts = new Map<number, number>();
    for (const m of matches) {
      const key = (m.scheduledAt as Date).getTime();
      counts.set(key, (counts.get(key) ?? 0) + 1);
    }
    // 30 distinct kickoff slots (15 first-leg + 15 second-leg).
    expect(counts.size).toBe(30);
    // The biggest legitimate collision is one matchday: 8 matches.
    expect(Math.max(...counts.values())).toBe(8);
  });

  it('REGRESSION: kickoffs land on MATCH_DAY_OFFSETS across the whole grid', () => {
    // Derived from the constants. The previous version spelled out
    // `[3,6,3,6,…]` (Wed/Sat) and gaps of `[3,4]` days, which stopped
    // describing the schedule the moment `MATCH_DAY_OFFSETS` changed.
    //
    // It also asserted `leg2[i] - leg1[i] === 15 * 7` — pinning the bug.
    // The second leg continues on the SAME grid, 15 slots later.
    const allTimes = [
      ...new Set(gen().map((m) => (m.scheduledAt as Date).getTime())),
    ].sort((a, b) => a - b);

    // One grid slot per round of the double round-robin.
    const totalSlots = 2 * (TEAM_IDS.length - 1);
    expect(allTimes).toHaveLength(totalSlots);

    // Weekday of each slot, Monday=0 to match MATCH_DAY_OFFSETS.
    const weekday = (t: number) => (new Date(t).getUTCDay() + 6) % 7;
    expect(allTimes.map(weekday)).toEqual(
      Array.from(
        { length: totalSlots },
        (_, i) =>
          GAME_SETTINGS.MATCH_DAY_OFFSETS[i % GAME_SETTINGS.ROUNDS_PER_WEEK],
      ),
    );

    // Consecutive slots are 2 or 3 days apart (and the wrap from the last
    // day of a week back to the first of the next is 3).
    const gaps = allTimes
      .map((t, i) => (i === 0 ? null : (t - allTimes[i - 1]) / 86_400_000))
      .slice(1) as number[];
    for (const g of gaps) {
      expect([2, 3]).toContain(g);
    }
  });

  it('REGRESSION: the week stamp agrees with the kickoff date', () => {
    // The core invariant. Before the fix every second-leg round carried a
    // `week` stamp 8 weeks behind its actual calendar week, and 13 of 15
    // were dated outside the season-year altogether.
    //
    // Assert with the derived value as the EXPECTED side — building both
    // sides from `m.week` makes the comparison trivially true and the
    // test passes against the very bug it is meant to catch.
    const msWeek = MS_WEEK;
    // START is a Monday, so the week-one anchor is START itself.
    const weekOneMonday = WEEK_ONE_MONDAY.getTime();

    const mismatches = gen()
      .map((m) => ({
        stamped: m.week as number,
        derived:
          Math.floor(
            ((m.scheduledAt as Date).getTime() - weekOneMonday) / msWeek,
          ) + 1,
      }))
      .filter(({ stamped, derived }) => stamped !== derived);

    // Show the distinct (stamped, derived) pairs rather than 120 rows.
    expect([...new Set(mismatches.map((m) => JSON.stringify(m)))]).toEqual([]);
  });

  it('REGRESSION: every match falls inside the season-year', () => {
    // The failure that actually shipped: leg 2 was scheduled 105 days
    // after leg 1, so its rounds 2..14 landed in the FOLLOWING season
    // while carrying this season's number.
    const msWeek = MS_WEEK;
    const weekOneMonday = WEEK_ONE_MONDAY.getTime();
    const seasonEnd =
      weekOneMonday + GAME_SETTINGS.SEASON_LENGTH_WEEKS * msWeek;

    for (const m of gen()) {
      const t = (m.scheduledAt as Date).getTime();
      expect({
        inSeason: t >= weekOneMonday && t < seasonEnd,
        week: m.week,
      }).toEqual({ inSeason: true, week: m.week });
    }
  });

  it('REGRESSION: no pairing meets twice inside one calendar week', () => {
    // Guards against the other tempting "fix" — dropping the offset
    // entirely, which gives leg-2 round r the same date as leg-1 round r.
    // That is the same pairing with mirrored home/away on the same day.
    const msWeek = MS_WEEK;
    const weekOneMonday = WEEK_ONE_MONDAY.getTime();
    const weekOf = (t: number) => Math.floor((t - weekOneMonday) / msWeek);

    const byPairing = new Map<string, number[]>();
    for (const m of gen()) {
      const key = [m.homeTeamId, m.awayTeamId].sort().join('|');
      byPairing.set(key, [
        ...(byPairing.get(key) ?? []),
        weekOf((m.scheduledAt as Date).getTime()),
      ]);
    }
    for (const [key, weeks] of byPairing) {
      expect({ key, distinct: new Set(weeks).size }).toEqual({
        key,
        distinct: 2,
      });
    }
  });

  it('REGRESSION: kickoff hour is MATCH_KICKOFF_HOUR_UTC', () => {
    for (const m of gen()) {
      expect((m.scheduledAt as Date).getUTCHours()).toBe(
        GAME_SETTINGS.MATCH_KICKOFF_HOUR_UTC,
      );
      expect((m.scheduledAt as Date).getUTCMinutes()).toBe(0);
    }
  });

  it('the second leg of each pairing is at least 7 days after the first', () => {
    const byPairing = new Map<string, number[]>();
    for (const m of gen()) {
      const key = [m.homeTeamId, m.awayTeamId].sort().join('|');
      const list = byPairing.get(key) ?? [];
      list.push((m.scheduledAt as Date).getTime());
      byPairing.set(key, list);
    }
    expect(byPairing.size).toBe((16 * 15) / 2);
    for (const [key, times] of byPairing) {
      expect(times).toHaveLength(2);
      const [a, b] = times.sort((x, y) => x - y);
      expect({ key, gapDays: (b - a) / (24 * 60 * 60 * 1000) }).toEqual({
        key,
        gapDays: expect.any(Number),
      });
      expect(b - a).toBeGreaterThanOrEqual(7 * 24 * 60 * 60 * 1000);
    }
  });

  it('every pairing plays once at each venue (double round-robin contract)', () => {
    const venues = new Map<string, Set<string>>();
    for (const m of gen()) {
      const key = [m.homeTeamId, m.awayTeamId].sort().join('|');
      const set = venues.get(key) ?? new Set<string>();
      set.add(`${m.homeTeamId}>${m.awayTeamId}`);
      venues.set(key, set);
    }
    for (const set of venues.values()) {
      expect(set.size).toBe(2);
    }
  });

  it('weeks stay within the season length so the transition crons can fire', () => {
    // `SeasonTransitionService` keys on `week`, and the playoff gate
    // checks that the last REGULAR week is complete. A schedule whose
    // `week` runs past that would silently never satisfy the gate.
    //
    // This asserts the *stamp*, so it could not have caught the
    // mis-stamped second leg (those stamps were always in range — only the
    // dates were wrong). The date-based tests above are what catch that.
    const weeks = gen().map((m) => m.week as number);
    const regularWeeks = GAME_SETTINGS.REGULAR_SEASON_WEEKS;

    expect(Math.min(...weeks)).toBe(1);
    expect(Math.max(...weeks)).toBe(regularWeeks);

    // Every regular week is actually used — no gaps that would leave a
    // matchday unplayed, and nothing spilling into the playoff week.
    expect([...new Set(weeks)].sort((a, b) => a - b)).toEqual(
      Array.from({ length: regularWeeks }, (_, i) => i + 1),
    );

    // ROUNDS_PER_WEEK fixtures per team per week, every week.
    const perWeek = new Map<number, number>();
    for (const m of gen()) {
      perWeek.set(m.week as number, (perWeek.get(m.week as number) ?? 0) + 1);
    }
    const fixturesPerMatchday = TEAM_IDS.length / 2;
    expect(
      [...perWeek.values()].every(
        (n) => n === fixturesPerMatchday * GAME_SETTINGS.ROUNDS_PER_WEEK,
      ),
    ).toBe(true);
  });

  it('stamps SCHEDULED / LEAGUE so the completion cron picks them up', () => {
    for (const m of gen()) {
      expect(m.status).toBe(MatchStatus.SCHEDULED);
      expect(m.type).toBe(MatchType.LEAGUE);
    }
  });

  describe('calculateNextSeasonStartDate', () => {
    const anchorFor = (initDate: Date, currentSeason: number): Date =>
      (service as any).calculateNextSeasonStartDate(initDate, currentSeason);

    it('is derived from the init date, not from the current clock', () => {
      // The old implementation walked forward from `new Date()` to the
      // next Wednesday and added 7 days. That is a function of WHEN the
      // cron fired, not of the calendar.
      jest.useFakeTimers();
      try {
        const results = [
          new Date('2026-04-07T00:00:00Z'), // Tue
          new Date('2026-04-09T00:00:00Z'), // Thu
          new Date('2026-07-15T12:00:00Z'), // months later, mid-week
        ].map((now) => {
          jest.setSystemTime(now);
          return anchorFor(INIT_DATE, 3).toISOString();
        });

        // Every fire time yields the same anchor.
        expect([...new Set(results)]).toHaveLength(1);
      } finally {
        jest.useRealTimers();
      }
    });

    it('lands on the season-N week-one Monday', () => {
      // Season 1 is anchored by `computeSeasonWeekOneMonday(initDate)` in
      // `ScheduleGenerator`; each later season is exactly
      // SEASON_LENGTH_WEEKS further on. Using a different anchor for
      // season 2+ is what let the two generators drift apart.
      const seasonOneMonday = computeSeasonWeekOneMonday(INIT_DATE);
      const msWeek = 7 * 24 * 60 * 60 * 1000;

      for (const currentSeason of [1, 2, 5, 12]) {
        const expected = new Date(
          seasonOneMonday.getTime() +
            currentSeason * GAME_SETTINGS.SEASON_LENGTH_WEEKS * msWeek,
        );
        expect({
          currentSeason,
          isMonday: anchorFor(INIT_DATE, currentSeason).getUTCDay(),
          matches: anchorFor(INIT_DATE, currentSeason).getTime(),
        }).toEqual({ currentSeason, isMonday: 1, matches: expected.getTime() });
      }
    });

    it('steps forward by whole weeks as the season count grows', () => {
      const msWeek = 7 * 24 * 60 * 60 * 1000;
      const a = anchorFor(INIT_DATE, 1).getTime();
      const b = anchorFor(INIT_DATE, 2).getTime();
      expect((b - a) / msWeek).toBe(GAME_SETTINGS.SEASON_LENGTH_WEEKS);
    });

    it('follows the system_config.init_date row, not the env var', () => {
      // `resolveInitDate` reads `system_config.init_date` first. If this
      // service resolved from `GAME_START_DATE` alone it would silently
      // disagree with `BootstrapService` (and therefore with season 1)
      // after the first init.
      const rowDate = new Date('2026-04-06T00:00:00.000Z'); // Mon
      dataSource.manager.findOne.mockResolvedValue({
        key: 'init_date',
        value: rowDate.toISOString(),
      });

      const expected = computeSeasonWeekOneMonday(rowDate);
      // Re-resolve through the service's own call path.
      return service.generateNextSeasonSchedule(1).then(() => {
        // `generateNextSeasonSchedule` computed a start date from the
        // row; assert the pure helper agrees for the same inputs.
        expect(anchorFor(rowDate, 1).getTime() - expected.getTime()).toBe(
          GAME_SETTINGS.SEASON_LENGTH_WEEKS * 7 * 24 * 60 * 60 * 1000,
        );
      });
    });

    it('agrees with the init date helper for a non-Monday init', () => {
      // `computeSeasonWeekOneMonday` pushes to the NEXT Monday, so a
      // Tuesday init anchors season 1 six days later. Whatever that rule
      // is, season 2+ must use the same one — the schedule's week N
      // living one week later than the clock's week N is load-bearing
      // (see the note on `generateDoubleRoundRobin`).
      const tuesday = new Date('2026-04-07T00:00:00.000Z');
      const seasonOneMonday = computeSeasonWeekOneMonday(tuesday);
      expect(startOfUtcDay(seasonOneMonday).getUTCDay()).toBe(1);
      expect(seasonOneMonday.getTime()).toBeGreaterThan(tuesday.getTime());
    });
  });

  /**
   * The two fixture generators must produce the SAME grid.
   *
   * Season 1 goes through `ScheduleGenerator`; seasons 2+ go through this
   * service. They were independent implementations and drifted: the second
   * leg's dates were offset by 105 days while its `week` stamp was not, so
   * 13 of 15 rounds were scheduled outside the season-year. Season 1 looked
   * correct the whole time, which is exactly why it survived a full season
   * and why no unit test caught it.
   *
   * This compares the two grids slot by slot. It is the assertion that would
   * have failed on day one of season 2.
   */
  describe('cross-generator: season 1 and season 2+ must agree', () => {
    /** The distinct (week, round, kickoff) slots of a generated fixture list. */
    const slotsOf = (matches: Partial<MatchEntity>[]) =>
      [
        ...new Set(
          matches.map((m) =>
            [m.week, m.round, (m.scheduledAt as Date).getTime()].join('|'),
          ),
        ),
      ].sort();

    let season1Gen: {
      generateSeason1Schedule: (initDate: Date) => Promise<void>;
    };
    let saved1: Partial<MatchEntity>[];

    beforeEach(() => {
      const mockLogger = {
        info: jest.fn(),
        warn: jest.fn(),
        debug: jest.fn(),
        error: jest.fn(),
      };
      const matchRepo = {
        count: jest.fn().mockResolvedValue(0),
        save: jest.fn().mockImplementation((rows: Partial<MatchEntity>[]) => {
          saved1 = rows;
          return Promise.resolve([]);
        }),
      };
      const leagueRepo = {
        find: jest.fn().mockResolvedValue([{ id: 'L-1', maxTeams: 16 }]),
      };
      const teamRepo = {
        find: jest
          .fn()
          .mockResolvedValue(
            TEAM_IDS.map((id) => ({ id, name: id, leagueId: 'L-1' })),
          ),
      };
      const stadiumRepo = {
        find: jest
          .fn()
          .mockImplementation(() =>
            Promise.resolve(
              TEAM_IDS.map((id) => ({ id: `st-${id}`, teamId: id })),
            ),
          ),
      };
      season1Gen = new ScheduleGenerator(
        mockLogger as never,
        matchRepo as never,
        leagueRepo as never,
        teamRepo as never,
        stadiumRepo as never,
      );
    });

    /**
     * `initDate` for `ScheduleGenerator`.
     *
     * `computeSeasonWeekOneMonday` always pushes to the NEXT Monday, so a
     * Monday input lands a week later. Feeding it the Monday *before*
     * `WEEK_ONE_MONDAY` anchors both generators on the same week. That
     * one-week gap between the schedule anchor and `currentSeasonWeek`'s
     * `gameStart` is load-bearing, not a bug — see the note on
     * `generateDoubleRoundRobin`.
     */
    const season1InitDate = new Date(
      WEEK_ONE_MONDAY.getTime() - 7 * 86_400_000,
    );

    /** Run the season-1 generator and return its saved fixture list. */
    const runSeason1 = async (): Promise<Partial<MatchEntity>[]> => {
      await season1Gen.generateSeason1Schedule(season1InitDate);
      return saved1;
    };

    it('produce an identical week / round / kickoff grid', async () => {
      const season1 = slotsOf(await runSeason1());
      const season2 = slotsOf(gen());

      expect({ generator: 'season 1', slots: season1.length }).toEqual({
        generator: 'season 1',
        slots: season2.length,
      });
      expect({
        generator: 'season 1',
        differing: season1.filter((s, i) => s !== season2[i]),
      }).toEqual({ generator: 'season 1', differing: [] });
    });

    it('agree on how many fixtures each team plays per week', async () => {
      const saved = await runSeason1();

      const perWeek = (matches: Partial<MatchEntity>[]) => {
        const counts = new Map<number, number>();
        const perMatchday = TEAM_IDS.length / 2;
        for (const m of matches) {
          const key = m.week as number;
          counts.set(key, (counts.get(key) ?? 0) + perMatchday);
        }
        return [...counts.entries()].sort((a, b) => a[0] - b[0]);
      };

      expect({ generator: 'season 1', load: perWeek(saved) }).toEqual({
        generator: 'season 1',
        load: perWeek(gen()),
      });
    });

    it('both end on the last regular week, not the playoff week', async () => {
      const saved = await runSeason1();

      const lastWeek = (matches: Partial<MatchEntity>[]) =>
        Math.max(...matches.map((m) => m.week as number));

      expect({
        generator: 'season 1',
        lastWeek: lastWeek(saved),
        playoffTriggerWeek: GAME_SETTINGS.SEASON_LENGTH_WEEKS - 1,
      }).toEqual({
        generator: 'season 1',
        lastWeek: lastWeek(gen()),
        playoffTriggerWeek: GAME_SETTINGS.SEASON_LENGTH_WEEKS - 1,
      });
    });
  });

  describe('generateNextSeasonSchedule idempotency', () => {
    it('REGRESSION: skips a league that already has a schedule for the season', async () => {
      // There was no guard at all, so a second
      // `checkAndProcessSeasonStart` run inserted a complete duplicate
      // fixture list (~20,400 rows) — teams playing every opponent
      // twice in the same week slots, with no unique constraint on
      // `match` to stop it. Reachable because that method
      // logs-and-rethrows: step 4 failing after steps 1-3 committed
      // means next week's cron re-runs it.
      leagueRepository.find.mockResolvedValue([
        { id: 'league-1', maxTeams: 16 } as any,
      ]);
      // Season 2 already has fixtures for this league.
      matchRepository.count.mockResolvedValue(240);

      const result = await service.generateNextSeasonSchedule(1);

      expect(result).toEqual([]);
      expect(matchRepository.save).not.toHaveBeenCalled();
      expect(standingRepository.find).not.toHaveBeenCalled();
      // The guard is keyed on (leagueId, season).
      expect(matchRepository.count).toHaveBeenCalledWith({
        where: { leagueId: 'league-1', season: 2 },
      });
    });

    it('emits a schedule when the league has none yet', async () => {
      leagueRepository.find.mockResolvedValue([
        { id: 'league-1', maxTeams: 16 } as any,
      ]);
      matchRepository.count.mockResolvedValue(0);
      standingRepository.find.mockResolvedValue(
        TEAM_IDS.map((id) => ({ teamId: id })),
      );

      const result = await service.generateNextSeasonSchedule(1);

      expect(matchRepository.save).toHaveBeenCalledTimes(1);
      expect(result).toHaveLength(16 * 15);
    });

    it('a second run over the same season is a no-op', async () => {
      leagueRepository.find.mockResolvedValue([
        { id: 'league-1', maxTeams: 16 } as any,
      ]);
      standingRepository.find.mockResolvedValue(
        TEAM_IDS.map((id) => ({ teamId: id })),
      );
      matchRepository.count.mockResolvedValue(0);

      await service.generateNextSeasonSchedule(1);
      const firstCount = matchRepository.save.mock.calls.length;
      expect(firstCount).toBe(1);

      // Simulate the first run having written the rows.
      matchRepository.count.mockResolvedValue(240);
      const second = await service.generateNextSeasonSchedule(1);

      expect(second).toEqual([]);
      expect(matchRepository.save).toHaveBeenCalledTimes(firstCount);
    });
  });
});
