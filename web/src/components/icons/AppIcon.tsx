export type MaterialIconName = keyof typeof ICON_MAP;

/** Names that reach AppIcon without an ICON_MAP entry (JS callers).
 *  Rendered as a visible dashed circle so QA greps can catch them,
 *  never as literal text. */
const warned = new Set<string>();
function warnOnce(name: string) {
  if (process.env.NODE_ENV !== "production" && !warned.has(name)) {
    warned.add(name);
    console.warn(`[AppIcon] no mapping for "${name}" — using placeholder`);
  }
}

export interface AppIconProps extends Omit<LucideProps, "fill"> {
  name: MaterialIconName;
  /** Default "1em": inherits the surrounding text-* size. */
  size?: number | string;
  /** Solid variant (Material `FILL 1`) for active/selected states. */
  fill?: boolean;
  /** Accessible name; omit for decorative icons (aria-hidden). */
  label?: string;
}

export function AppIcon({
  name,
  size = "1em",
  fill = false,
  label,
  style,
  ...rest
}: AppIconProps) {
  const Cmp = (ICON_MAP as Record<string, ComponentType<LucideProps> | undefined>)[name];
  const a11y = {
    "aria-hidden": label ? undefined : true,
    role: label ? ("img" as const) : undefined,
    "aria-label": label,
  };
  if (!Cmp) {
    warnOnce(name);
    return <CircleDashed {...rest} size={size} style={style} data-unresolved="true" {...a11y} />;
  }
  return (
    <Cmp
      {...rest}
      size={size}
      fill={fill ? "currentColor" : "none"}
      style={{ verticalAlign: "middle", ...style }}
      {...a11y}
    />
  );
}
