/**
 * AppIcon — the single entry point for every UI icon.
 *
 * Replaces the Material Symbols icon font (ligature <span>s) with
 * stroke SVGs. Every entry is a key of the original Material ligature
 * name, so call sites migrate mechanically and a typo fails to compile
 * instead of silently rendering literal text (the icon font's failure
 * mode).
 *
 * Conventions:
 * - `size` defaults to "1em" so existing `text-*` classes on the
 *   call site keep sizing the icon exactly as before.
 * - Decorative by default (`aria-hidden`); pass `label` when the icon
 *   is the only content of a control.
 * - `fill` is the Lucide equivalent of Material's `FILL 1` axis.
 *
 * Coverage: every Material ligature name found in the codebase.
 * Adding an icon = add it to ICON_MAP; MaterialIconName grows with it.
 */
